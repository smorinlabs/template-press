"""Declared ``Cargo.lock`` regeneration: suggestion, exemption, and the gate."""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import pytest

from template_press.rebrand.cli import main
from template_press.rebrand.discovery import cargo_problems
from template_press.rebrand.engine import REGENERATE_EXEMPTIBLE, scan_paths
from template_press.rebrand.rules import (
    DEFAULT_RULES,
    load_rules,
    regenerate_suggestion,
)

from .test_cargo_discovery import (
    CORE_MAP,
    ZETA_MAP,
    _answers,
    _crate,
    _git,
    _identity,
    _repo,
    _source_config,
)

BLOCK = (
    '[rules]\nextra_exclude_files = ["Cargo.lock"]\n\n'
    '[[regenerate]]\nfile = "Cargo.lock"\n'
    'command = ["cargo", "update", "--workspace", "--offline"]\n'
)
LOCK = (
    "# This file is automatically @generated by Cargo.\nversion = 4\n\n"
    '[[package]]\nname = "acme-core"\nversion = "0.1.0"\n'
)


def _files(extra: dict[str, str]) -> dict[str, str]:
    return {
        "Cargo.toml": _crate("acme-core"),
        "src/lib.rs": "pub fn hi() {}\n",
        "press/press-source.toml": _source_config(CORE_MAP),
        **extra,
    }


def test_cargo_lock_is_exempt_only_when_declared(tmp_path: Path) -> None:
    assert "Cargo.lock" in REGENERATE_EXEMPTIBLE
    declared = _repo(
        tmp_path, _files({"Cargo.lock": LOCK, "press/press-rules.toml": BLOCK})
    )
    rels = {e.rel.as_posix() for e in scan_paths(declared, load_rules(declared))}
    assert "Cargo.lock" not in rels


def test_cargo_lock_is_not_a_default_exclude() -> None:
    assert "Cargo.lock" not in DEFAULT_RULES.exclude_files


def test_suggestion_is_the_spec_block() -> None:
    assert regenerate_suggestion("Cargo.lock") == BLOCK
    assert regenerate_suggestion("sub/Cargo.lock") is None


def test_tracked_lock_without_regeneration_exits_2_with_hint(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = _repo(tmp_path, _files({"Cargo.lock": LOCK}))
    answers = _answers(tmp_path, ZETA_MAP)
    code = main(["--target", str(target), "--dry-run", "--config", str(answers)])
    out = capsys.readouterr().out
    assert code == 2
    assert "Cargo.lock" in out
    assert BLOCK in out
    assert _git(target, "status", "--porcelain") == ""


def test_tracked_lock_without_regeneration_refuses_in_cargo_problems(
    tmp_path: Path,
) -> None:
    target = _repo(tmp_path, _files({"Cargo.lock": LOCK}))
    problems = cargo_problems(target, _identity(CORE_MAP), None, load_rules(target))
    assert any("Cargo.lock" in p for p in problems)


def test_staged_only_lock_counts_as_tracked(tmp_path: Path) -> None:
    target = _repo(tmp_path, _files({}))
    (target / "Cargo.lock").write_text(LOCK, encoding="utf-8")
    _git(target, "add", "Cargo.lock")
    problems = cargo_problems(target, _identity(CORE_MAP), None, load_rules(target))
    assert any("Cargo.lock" in p for p in problems)


def test_tracked_but_ignored_lock_counts_as_tracked(tmp_path: Path) -> None:
    target = _repo(tmp_path, _files({".gitignore": "Cargo.lock\n"}))
    (target / "Cargo.lock").write_text(LOCK, encoding="utf-8")
    _git(target, "add", "-f", "Cargo.lock")
    _git(target, "commit", "-q", "-m", "track an ignored lock")
    problems = cargo_problems(target, _identity(CORE_MAP), None, load_rules(target))
    assert any("Cargo.lock" in p for p in problems)


def test_declared_lock_is_accepted(tmp_path: Path) -> None:
    target = _repo(
        tmp_path, _files({"Cargo.lock": LOCK, "press/press-rules.toml": BLOCK})
    )
    assert cargo_problems(target, _identity(CORE_MAP), None, load_rules(target)) == []


def test_untracked_or_absent_lock_needs_no_declaration(tmp_path: Path) -> None:
    absent = _repo(tmp_path, _files({}))
    assert cargo_problems(absent, _identity(CORE_MAP), None, load_rules(absent)) == []
    (absent / "Cargo.lock").write_text(LOCK, encoding="utf-8")  # untracked
    assert cargo_problems(absent, _identity(CORE_MAP), None, load_rules(absent)) == []


def test_lock_without_a_table_needs_no_declaration(tmp_path: Path) -> None:
    files = _files({"Cargo.lock": LOCK})
    del files["press/press-source.toml"]
    target = _repo(tmp_path, files)
    assert cargo_problems(target, _identity(), None, load_rules(target)) == []


def test_declared_python_excluding_rust_ignores_cargo_lock(tmp_path: Path) -> None:
    target = _repo(
        tmp_path,
        {
            "pyproject.toml": '[project]\nname = "acme-core"\n',
            "src/acme_core/__init__.py": "",
            "Cargo.toml": _crate("acme-core"),
            "Cargo.lock": LOCK,
            "press/press-source.toml": _source_config(CORE_MAP),
            "press/press-rules.toml": '[rules]\nlanguages = ["python"]\n',
        },
    )
    answers = _answers(tmp_path, ZETA_MAP)
    assert main(["--target", str(target), "--dry-run", "--config", str(answers)]) == 0


def _require_cargo() -> None:
    if shutil.which("cargo") is None:
        if os.environ.get("CI"):
            pytest.fail("cargo is required in CI")
        pytest.skip("cargo not installed")


def _vendor(root: Path, version: str) -> None:
    crate = root / "vendor" / f"dep-{version}"
    (crate / "src").mkdir(parents=True)
    (crate / "Cargo.toml").write_text(
        f'[package]\nname = "dep"\nversion = "{version}"\nedition = "2021"\n',
        encoding="utf-8",
    )
    (crate / "src" / "lib.rs").write_text("", encoding="utf-8")
    (crate / ".cargo-checksum.json").write_text(
        '{"files":{},"package":null}', encoding="utf-8"
    )


def _locked_dep_version(root: Path) -> str:
    text = (root / "Cargo.lock").read_text(encoding="utf-8")
    return text.split('name = "dep"\nversion = "')[1].split('"')[0]


@pytest.mark.slow
def test_update_workspace_preserves_vendored_version(tmp_path: Path) -> None:
    _require_cargo()
    root = tmp_path / "ws"
    (root / "src").mkdir(parents=True)
    (root / ".cargo").mkdir()
    (root / "src" / "lib.rs").write_text("", encoding="utf-8")
    (root / "Cargo.toml").write_text(
        '[package]\nname = "acme-core"\nversion = "0.1.0"\nedition = "2021"\n'
        '\n[dependencies]\ndep = "1"\n',
        encoding="utf-8",
    )
    (root / ".cargo" / "config.toml").write_text(
        '[source.crates-io]\nreplace-with = "vendored"\n\n'
        '[source.vendored]\ndirectory = "vendor"\n',
        encoding="utf-8",
    )
    _vendor(root, "1.0.0")

    cargo_home = tmp_path / "cargo-home"
    cargo_home.mkdir()

    def cargo(*argv: str) -> None:
        subprocess.run(  # noqa: S603
            ["cargo", *argv, "--offline"],  # noqa: S607
            cwd=root,
            env={**os.environ, "CARGO_HOME": str(cargo_home)},
            check=True,
            capture_output=True,
            text=True,
        )

    cargo("generate-lockfile")
    assert _locked_dep_version(root) == "1.0.0"
    _vendor(root, "1.1.0")
    cargo("update", "--workspace")
    assert _locked_dep_version(root) == "1.0.0"
    cargo("generate-lockfile")
    assert _locked_dep_version(root) == "1.1.0"
